// Builds the sample app's theme from design/system/theme.css, which stays the only source (D-38).
// `node scripts/sample-theme.ts` writes the files, `--check` fails when they are out of date.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const THEME_CSS = join(ROOT, "design/system/theme.css");
const FONT_SOURCE = join(ROOT, "design/fonts/Outfit[wght].ttf");
const SAMPLE_MAIN = join(ROOT, "sample-app/app/src/main");
const TOKENS_KT = join(SAMPLE_MAIN, "java/dev/jagra/sample/ui/theme/Tokens.kt");
const FONT_TARGET = join(SAMPLE_MAIN, "res/font/outfit.ttf");

const REM_IN_DP = 16;

/** The custom properties declared in one top-level rule, such as `:root` or `.dark`. */
export function readBlock(css: string, selector: string): Map<string, string> {
  const start = css.search(
    new RegExp(`^${selector.replace(/[.:]/g, "\\$&")}\\s*\\{`, "m"),
  );
  if (start < 0) throw new Error(`theme.css has no ${selector} block`);
  const body = css.slice(css.indexOf("{", start) + 1, css.indexOf("}", start));
  const tokens = new Map<string, string>();
  for (const [, name, value] of body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) {
    tokens.set(name, value.trim());
  }
  return tokens;
}

/** `oklch(L C H)` to `#RRGGBB`. Colors outside sRGB are clipped per channel. */
export function oklchToHex(value: string): string {
  const match = /^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*\)$/.exec(value);
  if (!match) throw new Error(`not an oklch() color: ${value}`);
  const [l, c, h] = match.slice(1).map(Number) as [number, number, number];
  const a = c * Math.cos((h * Math.PI) / 180);
  const b = c * Math.sin((h * Math.PI) / 180);

  // OKLab to linear sRGB, matrices from Björn Ottosson's OKLab definition.
  const l3 = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m3 = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s3 = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const linear = [
    4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3,
    -1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3,
    -0.0041960863 * l3 - 0.7034186147 * m3 + 1.707614701 * s3,
  ];
  return (
    "#" +
    linear
      .map((x) => {
        const v = x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
        const byte = Math.round(Math.min(1, Math.max(0, v)) * 255);
        return byte.toString(16).padStart(2, "0").toUpperCase();
      })
      .join("")
  );
}

function camel(name: string): string {
  return name.replace(/-(\w)/g, (_, ch: string) => ch.toUpperCase());
}

function colorTokens(tokens: Map<string, string>): [string, string][] {
  return [...tokens].filter(([, value]) => value.startsWith("oklch("));
}

/** `0.5rem` to dp. */
function remToDp(value: string): number {
  const match = /^([\d.]+)rem$/.exec(value);
  if (!match) throw new Error(`--radius is not in rem: ${value}`);
  return Number(match[1]) * REM_IN_DP;
}

/** The radius scale from the `@theme inline` block, each one `var(--radius)` plus or minus pixels. */
function radiusScale(css: string, radiusDp: number): [string, number][] {
  const scale: [string, number][] = [];
  for (const [, size, expression] of css.matchAll(
    /--radius-(\w+)\s*:\s*([^;]+);/g,
  )) {
    const plain = expression.trim();
    const calc = /^calc\(var\(--radius\)\s*([+-])\s*(\d+)px\)$/.exec(plain);
    if (plain === "var(--radius)") scale.push([size, radiusDp]);
    else if (calc)
      scale.push([
        size,
        radiusDp + (calc[1] === "+" ? 1 : -1) * Number(calc[2]),
      ]);
    else throw new Error(`cannot read --radius-${size}: ${plain}`);
  }
  return scale;
}

/** The Kotlin file the sample app's theme reads its values from. */
export function tokensKotlin(css: string): string {
  const light = readBlock(css, ":root");
  const dark = readBlock(css, ".dark");
  const colors = colorTokens(light);
  for (const [name] of colors) {
    if (!dark.has(name)) throw new Error(`.dark has no --${name}`);
  }
  const radius = light.get("radius");
  if (!radius) throw new Error(":root has no --radius");
  const radii = radiusScale(css, remToDp(radius));

  const palette = (tokens: Map<string, string>) =>
    colors
      .map(
        ([name]) =>
          `    ${camel(name)} = Color(0xFF${oklchToHex(tokens.get(name)!).slice(1)}),`,
      )
      .join("\n");

  return `// Generated by scripts/sample-theme.ts from design/system/theme.css. Do not edit.
// Run \`pnpm theme:sample\` after changing the theme.
package dev.jagra.sample.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

internal class Tokens(
${colors.map(([name]) => `    val ${camel(name)}: Color,`).join("\n")}
)

internal val LightTokens = Tokens(
${palette(light)}
)

internal val DarkTokens = Tokens(
${palette(dark)}
)

${radii.map(([size, dp]) => `internal val Radius${size[0].toUpperCase()}${size.slice(1)} = ${dp}.dp`).join("\n")}
`;
}

function readText(file: string): string | undefined {
  try {
    return readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  } catch {
    return undefined;
  }
}

function readBytes(file: string): Buffer | undefined {
  try {
    return readFileSync(file);
  } catch {
    return undefined;
  }
}

function main(check: boolean): number {
  const kotlin = tokensKotlin(readFileSync(THEME_CSS, "utf8"));
  const font = readFileSync(FONT_SOURCE);
  const stale: string[] = [];
  if (readText(TOKENS_KT) !== kotlin) stale.push(TOKENS_KT);
  if (!readBytes(FONT_TARGET)?.equals(font)) stale.push(FONT_TARGET);

  if (check) {
    for (const file of stale) {
      console.error(`Out of date: ${relative(ROOT, file)}`);
    }
    if (stale.length > 0) console.error("Run `pnpm theme:sample` to update.");
    return stale.length > 0 ? 1 : 0;
  }
  mkdirSync(dirname(TOKENS_KT), { recursive: true });
  mkdirSync(dirname(FONT_TARGET), { recursive: true });
  writeFileSync(TOKENS_KT, kotlin);
  writeFileSync(FONT_TARGET, font);
  for (const file of stale) console.log(`Wrote ${relative(ROOT, file)}`);
  return 0;
}

if (import.meta.main) {
  process.exitCode = main(process.argv.includes("--check"));
}
